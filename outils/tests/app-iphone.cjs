// Test de bout en bout : app iphone. Lancer d'abord « npm run serveurs » dans outils/.
const { chromium } = require('playwright');
const { spawn } = require('child_process');
const path = require('path');
const ROOT = path.resolve(__dirname, '..', '..');
const OUT = path.join(__dirname, 'captures');
require('fs').mkdirSync(OUT, { recursive: true });
(async () => {
const b = await chromium.launch();
const errs = [];
const c = await b.newContext({ viewport: { width: 1280, height: 720 } });
await c.addInitScript(() => { localStorage.setItem('jdl.welcomed', '1'); window.JDL_PEER = { host: '127.0.0.1', port: 9000, path: '/', secure: false, config: { iceServers: [] } }; window.JDL_MQTT = 'ws://127.0.0.1:8884/mqtt'; });
const p = await c.newPage();
p.on('pageerror', e => errs.push(e.message));
await p.route(/fonts\.(googleapis|gstatic)/, r => r.abort());
await p.route(/cdn\.jsdelivr\.net/, r => { const u = r.request().url(); const f = u.includes('peerjs') ? 'peerjs.min.js' : u.includes('qrcode') ? 'qrcode.js' : u.includes('mqtt') ? 'mqtt.min.js' : u.includes('Presets') ? 'butterchurnPresets.min.js' : 'butterchurn.min.js'; r.fulfill({ path: ROOT + '/vendor/' + f, contentType: 'application/javascript' }); });
await p.goto('http://localhost:8765/');
await p.click('#bMore'); await p.click('#bRemote'); await p.click('#bBeScreen');
await p.waitForSelector('#screenBox:not([hidden])', { timeout: 15000 });
const code = (await p.textContent('#screenCode')).trim();
console.log('screen code', code);
const c2 = await b.newContext({ viewport: { width: 1024, height: 768 } });
await c2.addInitScript(() => { localStorage.setItem('jdl.welcomed', '1'); window.JDL_PEER = { host: '127.0.0.1', port: 9000, path: '/', secure: false, config: { iceServers: [] } }; window.JDL_MQTT = 'ws://127.0.0.1:8884/mqtt'; });
const t2 = await c2.newPage(); t2.on('pageerror', e => errs.push('tablet: ' + e.message));
await t2.route(/fonts\.(googleapis|gstatic)/, r => r.abort());
await t2.route(/cdn\.jsdelivr\.net/, r => { const u = r.request().url(); const f = u.includes('peerjs') ? 'peerjs.min.js' : u.includes('qrcode') ? 'qrcode.js' : u.includes('mqtt') ? 'mqtt.min.js' : u.includes('Presets') ? 'butterchurnPresets.min.js' : 'butterchurn.min.js'; r.fulfill({ path: ROOT + '/vendor/' + f, contentType: 'application/javascript' }); });
await t2.goto('http://localhost:8765/?ecran=' + code);
await p.waitForTimeout(4000);
const ph = spawn('node', [path.join(__dirname, '..', 'faux-iphone.cjs'), 'ws://127.0.0.1:8884/mqtt', code, '8'], { stdio: ['ignore', 'pipe', 'pipe'] });
ph.stdout.on('data', d => process.stdout.write('[phone] ' + d)); ph.stderr.on('data', d => process.stdout.write('[phone err] ' + d));
await p.waitForTimeout(3000);
console.log('during:', await p.textContent('#screenStatus'), '|', await p.textContent('#statusText'), '| bpm', await p.$eval('#bpm', e => e.hidden ? '-' : e.textContent));
await p.keyboard.press('Escape'); await p.waitForTimeout(4000);
console.log('tablet (extra screen):', await t2.textContent('#statusText'), '| meter', await t2.$eval('#mBass', e => e.style.transform), '| main shows', await p.textContent('#screenExtra'));
console.log('bpm after 7 s:', await p.$eval('#bpm', e => e.hidden ? '-' : e.textContent));
await p.screenshot({ path: OUT + '/iphone-feed.png' });
await p.waitForTimeout(5000);
console.log('after phone stopped:', await p.textContent('#statusText'));
console.log('errors:', errs.length ? errs : 'none');
await b.close();
})();
